# Duplicate Removal
nums = [10, 20, 30, 20, 10, 40]

unique_numbers = set(nums)

print("After Removing Duplicates:", unique_numbers)

# Common Elements
set1 = {10, 20, 30, 40}
set2 = {30, 40, 50, 60}

print("Common Elements:", set1 & set2)

# Unique Count
nums = [1, 2, 3, 2, 1, 4, 5, 4]

print("Unique Count:", len(set(nums)))